"""Write tbl/jp.tbl from the cp932 codec: printable ASCII, half-width kana and every double-byte character.

Characters that have two cp932 codes keep their first; tbl.py decodes the alias as [XX][XX], so the table stays roundtrip-exact.
[ ] { } decode as hex: tbl.py uses them for escapes."""
from pathlib import Path

CTRL = {b"\x81\x97": "{br}"}  # ＠ ends a line (docs/re/text.md)

lines = ["# Shift-JIS, generated by tools/make_jp_tbl.py. Do not edit by hand."]
for code, val in CTRL.items():
    lines.append(f"{code.hex().upper()}={val}")
for b in list(range(0x20, 0x7f)) + list(range(0xa1, 0xe0)):
    ch = bytes([b]).decode("cp932")
    if ch not in "[]{}":
        lines.append(f"{b:02X}=" + ("\\s" if b == 0x20 else ch))
seen = set()
for hi in list(range(0x81, 0xa0)) + list(range(0xe0, 0xfd)):
    for lo in range(0x40, 0xfd):
        code = bytes([hi, lo])
        if code in CTRL:
            continue
        try:
            ch = code.decode("cp932")
        except UnicodeDecodeError:
            continue
        if ch not in seen and ch.encode("cp932") == code:
            seen.add(ch)
            lines.append(f"{code.hex().upper()}={ch}")
out = Path(__file__).resolve().parents[1] / "tbl" / "jp.tbl"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(out, len(lines))
